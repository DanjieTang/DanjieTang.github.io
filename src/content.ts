// Everything the site says lives in this file. Anything wrapped in todo(...)
// (import it from './lib/todo') shows up as an "OWNER:" chip during
// `npm run dev` and is hidden in the production build.
//
// Images and files go in public/ and are referenced without a leading slash,
// e.g. 'images/profile.webp' for public/images/profile.webp.

import type { OrTodo } from './lib/todo'

export type Link = { label: string; href: OrTodo<string> }

export type Image = {
  src: OrTodo<string>
  alt: string
  caption?: string
  /** Show the caption as an intro line above the image instead of below it. */
  captionAbove?: boolean
  /** Cap the displayed width in px and centre it (for tall screenshots). */
  maxWidth?: number
  /** Which part stays visible when the photo is cropped to fill a tile (CSS object-position). */
  objectPosition?: string
}

/** One tile in the Personal section; more than one photo makes it swipeable. */
export type Album = { title: string; photos: Image[] }

export type Role = { title: string; org: string; dates: string }

export type Paper = { title: string; href?: string }

export type Benchmark = {
  name: string
  speedup: OrTodo<string>
  measuredOn: OrTodo<string>
}

export type Project = {
  id: string
  eyebrow?: string
  title: string
  summary: string
  links: Link[]
  highlights?: string[]
  authors?: string[]
  role?: OrTodo<string>
  learned?: OrTodo<string>
  /** 'top' sits in a framed panel above the highlights (model samples);
   *  'bottom' runs full width at the end of the card (screenshots). */
  figure?: Image & { position: 'top' | 'bottom' }
  benchmarks?: { title: string; rows: Benchmark[]; note: string }
  readingList?: OrTodo<Paper[]>
}

export type Publication = {
  authors: OrTodo<string[]>
  title: string
  venue: string
  /** Your authorship, e.g. 'Co-first author'. */
  role?: string
  /** Update by hand from Google Scholar now and then. */
  citations?: number
  summary?: string
  links: Link[]
}

